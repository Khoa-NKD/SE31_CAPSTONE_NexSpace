-- Contracts are separate from verification documents. Existing approvals remain unchanged.
CREATE TABLE organizer_contract (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    created_at DATETIME(6) DEFAULT NULL,
    updated_at DATETIME(6) DEFAULT NULL,
    organizer_profile_id BIGINT NOT NULL,
    contract_number VARCHAR(80) NOT NULL,
    template_version VARCHAR(60) NOT NULL,
    status VARCHAR(30) NOT NULL,
    demo BIT(1) NOT NULL,
    issued_at DATETIME(6) NOT NULL,
    content_snapshot LONGTEXT NOT NULL,
    content_hash VARCHAR(64) NOT NULL,
    original_pdf_key VARCHAR(80) NOT NULL,
    signed_pdf_key VARCHAR(80) DEFAULT NULL,
    signed_pdf_hash VARCHAR(64) DEFAULT NULL,
    signing_email VARCHAR(255) NOT NULL,
    signed_at DATETIME(6) DEFAULT NULL,
    signed_by BIGINT DEFAULT NULL,
    otp_hash VARCHAR(100) DEFAULT NULL,
    otp_expires_at DATETIME(6) DEFAULT NULL,
    otp_sent_at DATETIME(6) DEFAULT NULL,
    otp_attempts INT NOT NULL DEFAULT 0,
    otp_window_start DATETIME(6) DEFAULT NULL,
    otp_window_count INT NOT NULL DEFAULT 0,
    CONSTRAINT ux_organizer_contract_profile UNIQUE (organizer_profile_id),
    CONSTRAINT ux_organizer_contract_number UNIQUE (contract_number),
    CONSTRAINT fk_contract_profile FOREIGN KEY (organizer_profile_id) REFERENCES organizer_profile(id) ON DELETE RESTRICT,
    CONSTRAINT fk_contract_signer FOREIGN KEY (signed_by) REFERENCES users(id) ON DELETE RESTRICT,
    CONSTRAINT ck_contract_status CHECK (status IN ('PENDING_SIGNATURE', 'SIGNED', 'VOIDED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;
